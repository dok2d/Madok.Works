import "testing"

func TestTranslateSQLiteIdentity(t *testing.T) {
	cases := []string{
		"SELECT * FROM tasks WHERE id=?",
		"INSERT INTO t(a,b) VALUES(?,?)",
		"SELECT name FROM x ORDER BY name COLLATE NOCASE",
		"UPDATE t SET updated_at=datetime('now') WHERE id=?",
	}
	for _, q := range cases {
		if got := translate(dialectSQLite, q); got != q {
			t.Errorf("sqlite translate changed %q -> %q", q, got)
		}
	}
}

func TestTranslatePostgres(t *testing.T) {
	cases := []struct{ in, want string }{
		{"SELECT * FROM tasks WHERE id=?", "SELECT * FROM tasks WHERE id=$1"},
		{"INSERT INTO t(a,b) VALUES(?,?)", "INSERT INTO t(a,b) VALUES($1,$2)"},
		{"UPDATE t SET x=? WHERE id=? AND y=?", "UPDATE t SET x=$1 WHERE id=$2 AND y=$3"},
		{"UPDATE t SET updated_at=datetime('now') WHERE id=?", "UPDATE t SET updated_at=CURRENT_TIMESTAMP WHERE id=$1"},
		{"SELECT name FROM x ORDER BY name COLLATE NOCASE", "SELECT name FROM x ORDER BY LOWER(name)"},
		{"SELECT * FROM x ORDER BY c.name COLLATE NOCASE", "SELECT * FROM x ORDER BY LOWER(c.name)"},
		{"SELECT * FROM x ORDER BY COALESCE(parent_id,0), position, title COLLATE NOCASE", "SELECT * FROM x ORDER BY COALESCE(parent_id,0), position, LOWER(title)"},
		// ? inside a string literal must NOT be renumbered.
		{"SELECT * FROM x WHERE label='a?b' AND id=?", "SELECT * FROM x WHERE label='a?b' AND id=$1"},
	}
	for _, c := range cases {
		if got := translate(dialectPostgres, c.in); got != c.want {
			t.Errorf("translate(pg, %q) = %q, want %q", c.in, got, c.want)
		}
	}
}

func TestTranslateDDLPostgres(t *testing.T) {
	cases := []struct{ in, want string }{
		{"id INTEGER PRIMARY KEY AUTOINCREMENT", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"},
		{"created_at DATETIME NOT NULL DEFAULT (datetime('now'))", "created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP"},
		{"created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP", "created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP"},
		{"data BLOB NOT NULL", "data BYTEA NOT NULL"},
		{"is_admin INTEGER NOT NULL DEFAULT 0", "is_admin INTEGER NOT NULL DEFAULT 0"}, // booleans stay INTEGER
		{"ALTER TABLE comments ADD COLUMN updated_at DATETIME", "ALTER TABLE comments ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ"},
		{"ALTER TABLE users ADD COLUMN role TEXT NOT NULL DEFAULT 'regular'", "ALTER TABLE users ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'regular'"},
	}
	for _, c := range cases {
		if got := translateDDL(dialectPostgres, c.in); got != c.want {
			t.Errorf("translateDDL(pg, %q) = %q, want %q", c.in, got, c.want)
		}
	}
}

