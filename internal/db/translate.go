package db

import (
	"regexp"
	"strconv"
	"strings"
)

// dialect identifies the SQL backend a Store talks to. The codebase is written
// in SQLite's dialect; translate()/translateDDL() adapt those strings for
// Postgres at call time so the ~300 query sites stay untouched.
type dialect int

const (
	dialectSQLite dialect = iota
	dialectPostgres
)

// collateNocaseRe matches "<expr> COLLATE NOCASE" (all 9 uses are ORDER BY
// terms over a simple, possibly-qualified column reference).
var collateNocaseRe = regexp.MustCompile(`(?i)([\w.]+)\s+COLLATE\s+NOCASE`)

// translate rewrites a runtime query from the project's SQLite dialect into the
// target dialect. For SQLite it is the identity. For Postgres it:
//   - rewrites "<expr> COLLATE NOCASE" → LOWER(<expr>) (no ICU dependency)
//   - rewrites datetime('now') → CURRENT_TIMESTAMP
//   - renumbers ? placeholders to $1,$2,… (skipping ? inside '…' literals)
func translate(d dialect, q string) string {
	if d != dialectPostgres {
		return q
	}
	q = collateNocaseRe.ReplaceAllString(q, "LOWER($1)")
	q = strings.ReplaceAll(q, "datetime('now')", "CURRENT_TIMESTAMP")
	q = renumberPlaceholders(q)
	return q
}

// renumberPlaceholders converts ? to $1,$2,… left-to-right, leaving any ? that
// appears inside a single-quoted SQL string literal alone.
func renumberPlaceholders(q string) string {
	var b strings.Builder
	b.Grow(len(q) + 8)
	n := 0
	inStr := false
	for i := 0; i < len(q); i++ {
		c := q[i]
		if c == '\'' {
			inStr = !inStr
			b.WriteByte(c)
			continue
		}
		if c == '?' && !inStr {
			n++
			b.WriteByte('$')
			b.WriteString(strconv.Itoa(n))
			continue
		}
		b.WriteByte(c)
	}
	return b.String()
}

var addColumnRe = regexp.MustCompile(`(?i)(ALTER TABLE\s+\S+\s+ADD COLUMN\s+)`)

// translateDDL adapts a schema statement (CREATE TABLE / ALTER / INDEX) for the
// target dialect. SQLite is the identity. For Postgres it maps SQLite type
// idioms to their Postgres equivalents. Crucially it keeps INTEGER columns as
// INTEGER (the codebase stores booleans as 0/1 and compares with =0/=1).
func translateDDL(d dialect, q string) string {
	if d != dialectPostgres {
		return q
	}
	// Order matters: handle the AUTOINCREMENT PK idiom and the datetime('now')
	// default before the bare DATETIME type token.
	q = strings.ReplaceAll(q, "INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
	q = strings.ReplaceAll(q, "DEFAULT (datetime('now'))", "DEFAULT CURRENT_TIMESTAMP")
	q = strings.ReplaceAll(q, "DATETIME", "TIMESTAMPTZ")
	q = strings.ReplaceAll(q, "BLOB", "BYTEA")
	// Make ALTER TABLE ADD COLUMN idempotent (SQLite relied on swallowed
	// "duplicate column" errors; Postgres needs IF NOT EXISTS).
	if strings.Contains(strings.ToUpper(q), "ADD COLUMN") && !strings.Contains(strings.ToUpper(q), "IF NOT EXISTS") {
		q = addColumnRe.ReplaceAllString(q, "${1}IF NOT EXISTS ")
	}
	return q
}
