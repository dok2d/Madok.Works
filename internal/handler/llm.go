// LLM integration: an external OpenAI-compatible chat API (llama.cpp's server,
// or any standard endpoint). Configured by an admin under Integrations; when
// successfully enabled it powers the wiki page "Summary" button.

const (
	llmHTTPTimeout     = 7 * time.Minute // models can be slow; summaries run in the background
	llmTestTimeout     = 10 * time.Second
	llmSummaryMaxChars = 24000 // cap the page text sent to the model
)

// Summaries are generated by a background goroutine so they don't depend on the
// client staying connected; llmJobs tracks in-flight work per page revision to
// dedupe concurrent requests and let the client poll for completion.
var (
	llmJobMu sync.Mutex
	llmJobs  = map[string]*llmJob{}
)

type llmJob struct {
	done bool
	err  string
}

// llmStartJob marks a job in-flight; returns false if one is already running.
func llmStartJob(key string) bool {
	llmJobMu.Lock()
	defer llmJobMu.Unlock()
	if j, ok := llmJobs[key]; ok && !j.done {
		return false
	}
	llmJobs[key] = &llmJob{}
	return true
}

func llmFinishJob(key, errMsg string) {
	llmJobMu.Lock()
	defer llmJobMu.Unlock()
	if j, ok := llmJobs[key]; ok {
		j.done, j.err = true, errMsg
	}
}

// llmJobState reports "pending" / "error" / "none" for a poll (the cache is the
// source of truth for success, checked by the caller before this).
func llmJobState(key string) (status, errMsg string) {
	llmJobMu.Lock()
	defer llmJobMu.Unlock()
	j, ok := llmJobs[key]
	if !ok {
		return "none", ""
	}
	if !j.done {
		return "pending", ""
	}
	e := j.err
	delete(llmJobs, key)
	if e != "" {
		return "error", e
	}
	return "none", "" // done but no cached result found — treat as gone
}

func llmClearJob(key string) {
	llmJobMu.Lock()
	defer llmJobMu.Unlock()
	delete(llmJobs, key)
}

type llmConfig struct {
	Enabled bool
	BaseURL string // e.g. http://host:8080/v1
	APIKey  string
	Model   string
	NoThink bool // disable reasoning ("thinking") for faster answers (Qwen3-style)
}

func (h *Handler) llmConfig() llmConfig {
	return llmConfig{
		Enabled: h.store.GetSetting("llm_enabled") == "true",
		BaseURL: strings.TrimRight(strings.TrimSpace(h.store.GetSetting("llm_base_url")), "/"),
		APIKey:  h.store.GetSetting("llm_api_key"),
		Model:   strings.TrimSpace(h.store.GetSetting("llm_model")),
		NoThink: h.store.GetSetting("llm_no_think") == "true",
	}
}

func boolStr(b bool) string {
	if b {
		return "true"
	}
	return "false"
}

// llmSystem appends a no-think directive to the system prompt when the admin
// disabled reasoning. "/no_think" is the Qwen3 convention; for other models it's
// harmless text, and the <think> stripping below still applies regardless.
func llmSystem(c llmConfig, system string) string {
	if c.NoThink {
		return strings.TrimSpace(system) + " /no_think"
	}
	return system
}

// llmEnabled reports whether the wiki summary feature should be offered.
func (h *Handler) llmEnabled() bool {
	c := h.llmConfig()
	return c.Enabled && c.BaseURL != ""
}

// llmTest verifies the endpoint is reachable (GET {base}/models). It is the gate
// for "successfully enabled".
func llmTest(c llmConfig) error {
	if c.BaseURL == "" {
		return fmt.Errorf("base URL is required")
	}
	req, err := http.NewRequest(http.MethodGet, c.BaseURL+"/models", nil)
	if err != nil {
		return err
	}
	if c.APIKey != "" {
		req.Header.Set("Authorization", "Bearer "+c.APIKey)
	}
	resp, err := (&http.Client{Timeout: llmTestTimeout}).Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	io.Copy(io.Discard, io.LimitReader(resp.Body, 1<<20))
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("server returned %s", resp.Status)
	}
	return nil
}

// llmSummarize asks the model for a concise summary of the given text.
func llmSummarize(c llmConfig, text string) (string, error) {
	if len(text) > llmSummaryMaxChars {
		text = text[:llmSummaryMaxChars]
	}
	payload := map[string]any{
		"model": c.Model,
		"messages": []map[string]string{
			{"role": "system", "content": llmSystem(c, "You are a concise technical writer. Summarize the wiki page provided by the user. First line: a short title (≤6 words, no markdown, no 'Title:' prefix). Then a blank line, then a short paragraph or a few bullet points. Reply in the same language as the page. Output only the title and summary, no preamble.")},
			{"role": "user", "content": text},
		},
		"temperature": 0.3,
		"stream":      false,
	}
	body, _ := json.Marshal(payload)
	req, err := http.NewRequest(http.MethodPost, c.BaseURL+"/chat/completions", bytes.NewReader(body))
	if err != nil {
		return "", err
	}
	req.Header.Set("Content-Type", "application/json")
	if c.APIKey != "" {
		req.Header.Set("Authorization", "Bearer "+c.APIKey)
	}
	resp, err := (&http.Client{Timeout: llmHTTPTimeout}).Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	raw, _ := io.ReadAll(io.LimitReader(resp.Body, 4<<20))
	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("%s: %s", resp.Status, strings.TrimSpace(string(raw)))
	}
	var out struct {
		Choices []struct {
			Message struct {
				Content string `json:"content"`
			} `json:"message"`
		} `json:"choices"`
	}
	if err := json.Unmarshal(raw, &out); err != nil {
		return "", err
	}
	if len(out.Choices) == 0 {
		return "", fmt.Errorf("empty response from model")
	}
	content := out.Choices[0].Message.Content
	// Some reasoning models prepend a <think>…</think> block — keep only the answer.
	if i := strings.LastIndex(content, "</think>"); i >= 0 {
		content = content[i+len("</think>"):]
	}
	content = strings.TrimSpace(content)
	if content == "" {
		return "", fmt.Errorf("empty response from model")
	}
	return content, nil
}

// llmChat is a minimal one-shot chat completion (system + user → assistant text),
// stripping any <think> reasoning block. Shared by summary/task generation.
func llmChat(c llmConfig, system, user string, temperature float64) (string, error) {
	payload := map[string]any{
		"model": c.Model,
		"messages": []map[string]string{
			{"role": "system", "content": llmSystem(c, system)},
			{"role": "user", "content": user},
		},
		"temperature": temperature,
		"stream":      false,
	}
	body, _ := json.Marshal(payload)
	req, err := http.NewRequest(http.MethodPost, c.BaseURL+"/chat/completions", bytes.NewReader(body))
	if err != nil {
		return "", err
	}
	req.Header.Set("Content-Type", "application/json")
	if c.APIKey != "" {
		req.Header.Set("Authorization", "Bearer "+c.APIKey)
	}
	resp, err := (&http.Client{Timeout: llmHTTPTimeout}).Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	raw, _ := io.ReadAll(io.LimitReader(resp.Body, 4<<20))
	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("%s: %s", resp.Status, strings.TrimSpace(string(raw)))
	}
	var out struct {
		Choices []struct {
			Message struct {
				Content string `json:"content"`
			} `json:"message"`
		} `json:"choices"`
	}
	if err := json.Unmarshal(raw, &out); err != nil {
		return "", err
	}
	if len(out.Choices) == 0 {
		return "", fmt.Errorf("empty response from model")
	}
	content := out.Choices[0].Message.Content
	if i := strings.LastIndex(content, "</think>"); i >= 0 {
		content = content[i+len("</think>"):]
	}
	return strings.TrimSpace(content), nil
}

// llmGenerateTask asks the model for a task description and a TODO checklist
// (markdown) from a title/prompt, returning (description, todoMarkdown).
func llmGenerateTask(c llmConfig, title, prompt string) (string, string, error) {
	sys := "You help write software task tickets. Given a task title and optional notes, " +
		"reply with STRICT JSON: {\"description\": string (a clear markdown description), " +
		"\"todo\": [string, ...] (a short actionable checklist, 3-7 items)}. " +
		"Reply in the same language as the title. Output only the JSON, no preamble or code fences."
	user := "Title: " + title
	if strings.TrimSpace(prompt) != "" {
		user += "\nNotes: " + prompt
	}
	content, err := llmChat(c, sys, user, 0.4)
	if err != nil {
		return "", "", err
	}
	// Tolerate code fences around the JSON.
	content = strings.TrimSpace(content)
	content = strings.TrimPrefix(content, "```json")
	content = strings.TrimPrefix(content, "```")
	content = strings.TrimSuffix(content, "```")
	if i := strings.Index(content, "{"); i > 0 {
		content = content[i:]
	}
	if j := strings.LastIndex(content, "}"); j >= 0 {
		content = content[:j+1]
	}
	var parsed struct {
		Description string   `json:"description"`
		Todo        []string `json:"todo"`
	}
	if err := json.Unmarshal([]byte(content), &parsed); err != nil {
		// Fall back to using the whole reply as the description.
		return content, "", nil
	}
	var todo strings.Builder
	for _, item := range parsed.Todo {
		item = strings.TrimSpace(item)
		if item != "" {
			todo.WriteString("- [ ] " + item + "\n")
		}
	}
	return strings.TrimSpace(parsed.Description), strings.TrimSpace(todo.String()), nil
}

// handleLLMGenerateTask generates a task description + TODO checklist via the LLM.
func (h *Handler) handleLLMGenerateTask(w http.ResponseWriter, r *http.Request) {
	user := h.currentUser(r)
	if user == nil {
		http.Error(w, "unauthorized", http.StatusUnauthorized)
		return
	}
	if user.Role == "readonly" {
		http.Error(w, "read-only access", http.StatusForbidden)
		return
	}
	c := h.llmConfig()
	if !c.Enabled || c.BaseURL == "" {
		http.Error(w, "LLM not configured", http.StatusServiceUnavailable)
		return
	}
	var req struct {
		Title  string `json:"title"`
		Prompt string `json:"prompt"`
	}
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil || strings.TrimSpace(req.Title) == "" {
		http.Error(w, "title required", http.StatusBadRequest)
		return
	}
	// The model may take a while; allow a longer write deadline (as summary does).
	if rc := http.NewResponseController(w); rc != nil {
		rc.SetWriteDeadline(time.Now().Add(llmHTTPTimeout + 5*time.Second))
	}
	desc, todo, err := llmGenerateTask(c, strings.TrimSpace(req.Title), req.Prompt)
	if err != nil {
		http.Error(w, err.Error(), http.StatusBadGateway)
		return
	}
	jsonResp(w, map[string]string{"description": desc, "todo": todo})
}

