// handleWikiPageSummary serves an LLM summary of a wiki page, cached per
// revision. POST starts generation (in the background, so it survives the client
// navigating away) and returns immediately; GET polls. Either returns the cached
// result as soon as it is ready.
//
//	{status:"ready",   summary, cached, rev_no}
//	{status:"pending", rev_no}
//	{status:"error",   error, rev_no}
func (h *Handler) handleWikiPageSummary(w http.ResponseWriter, r *http.Request, page *model.WikiPage) {
	if r.Method != http.MethodPost && r.Method != http.MethodGet {
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
		return
	}
	if !h.llmEnabled() {
		http.Error(w, "LLM integration is not enabled", http.StatusForbidden)
		return
	}
	key := fmt.Sprintf("%d:%d", page.ID, page.RevNo)

	// Cache is the source of truth: serve it whenever present.
	if cached, ok := h.store.GetWikiSummary(page.ID, page.RevNo); ok {
		llmClearJob(key)
		jsonResp(w, map[string]any{"status": "ready", "summary": cached, "cached": true, "rev_no": page.RevNo})
		return
	}

	if r.Method == http.MethodGet {
		status, errMsg := llmJobState(key)
		jsonResp(w, map[string]any{"status": status, "error": errMsg, "rev_no": page.RevNo})
		return
	}

	// POST: kick off generation unless one is already running for this revision.
	text := strings.TrimSpace(db.WikiPagePlainText(page))
	if text == "" {
		http.Error(w, "page is empty", http.StatusBadRequest)
		return
	}
	if llmStartJob(key) {
		cfg := h.llmConfig()
		pageID, revNo := page.ID, page.RevNo
		go func() {
			summary, err := llmSummarize(cfg, text)
			if err != nil {
				h.logf("llm summarize page %d: %v", pageID, err)
				llmFinishJob(key, err.Error())
				return
			}
			if err := h.store.SaveWikiSummary(pageID, revNo, summary, cfg.Model); err != nil {
				h.logf("save summary: %v", err)
				llmFinishJob(key, "save failed")
				return
			}
			llmFinishJob(key, "")
		}()
	}
	jsonResp(w, map[string]any{"status": "pending", "rev_no": page.RevNo})
}
